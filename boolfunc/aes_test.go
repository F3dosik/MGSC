// componentFunc возвращает компонентную функцию f_b(x) = <b, S(x)> над GF(2),
// где <a,b> — скалярное произведение битов.
// b — маска выходных битов, x пробегает все 256 входов.
func componentFunc(sbox [256]uint8, b uint8) *BoolFunc {
	tv := make([]uint8, 256)
	for x := range 256 {
		// скалярное произведение над GF(2): popcount(b & sbox[x]) mod 2
		v := b & sbox[x]
		// подсчёт чётности через XOR всех битов
		v ^= v >> 4
		v ^= v >> 2
		v ^= v >> 1
		tv[x] = v & 1
	}
	f, _ := FromSlice(tv)
	return f
}

// TestAES_Nonlinearity проверяет что минимальная нелинейность по всем
// компонентным функциям AES S-блока равна 112 (уровень FIPS 197).
func TestAES_Nonlinearity(t *testing.T) {
	minNL := int(^uint(0) >> 1) // MaxInt
	for b := 1; b <= 255; b++ {
		f := componentFunc(aesSBox, uint8(b))
		nl := f.Nonlinearity()
		if nl < minNL {
			minNL = nl
		}
	}
	if minNL != 112 {
		t.Errorf("минимальная нелинейность AES = %d, хотим 112", minNL)
	}
}

// TestAES_AlgebraicDegree проверяет что максимальная алгебраическая степень
// компонентных функций AES S-блока равна 7.
func TestAES_AlgebraicDegree(t *testing.T) {
	maxDeg := 0
	for b := 1; b <= 255; b++ {
		f := componentFunc(aesSBox, uint8(b))
		d := f.AlgebraicDegree()
		if d > maxDeg {
			maxDeg = d
		}
	}
	if maxDeg != 7 {
		t.Errorf("максимальная степень AES = %d, хотим 7", maxDeg)
	}
}

// TestAES_Balanced проверяет что все компонентные функции AES сбалансированы.
func TestAES_Balanced(t *testing.T) {
	for b := 1; b <= 255; b++ {
		f := componentFunc(aesSBox, uint8(b))
		if !f.IsBalanced() {
			t.Errorf("компонентная функция b=0x%02x не сбалансирована (weight=%d)", b, f.Weight())
		}
	}
}
